// Dev utility: walk the Mirror journey and capture screenshots of each stage.
import { chromium } from '@playwright/test';
const [,, base = 'http://localhost:3100', outDir = '.', w = '390', h = '844'] = process.argv;
const browser = await chromium.launch();
const ctx = await browser.newContext({ viewport: { width: +w, height: +h } });
await ctx.addInitScript(() => { window.__AFM_TEST__ = { timeScale: 1 }; });
const page = await ctx.newPage();
const errors = [];
page.on('console', (m) => { if (m.type() === 'error') errors.push(m.text()); });
page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
const shot = async (name) => { await page.waitForTimeout(1500); await page.screenshot({ path: `${outDir}/${w}-${name}.png` }); };
await page.goto(`${base}/mirror`);
await page.getByTestId('onboarding').waitFor();
await shot('01-onboarding');
for (let i = 0; i < 3; i++) await page.getByTestId('onboarding-next').click();
await shot('02-onboarding-enter');
await page.getByTestId('onboarding-enter').click();
await page.getByTestId('weather-step').waitFor();
await shot('03-weather');
await page.getByTestId('weather-tense').click();
await page.getByTestId('consent-step').waitFor();
await shot('04-consent');
await page.getByTestId('start-arc').click();
await page.getByTestId('arc-storm').waitFor();
await page.waitForTimeout(2500);
await shot('05-storm');
await page.getByTestId('skip').click();
await page.getByTestId('arc-stillness').waitFor();
await page.waitForTimeout(5000);
await shot('06-stillness');
await page.getByTestId('skip').click();
await page.getByTestId('arc-song').waitFor();
await page.waitForTimeout(3500);
await shot('07-song');
await page.getByTestId('ground-me').click();
await page.getByTestId('ground-view').waitFor();
await shot('08-ground');
console.log(JSON.stringify(errors));
await browser.close();
